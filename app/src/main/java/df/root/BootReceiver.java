package df.root;

import android.content.BroadcastReceiver;
import android.content.Context;
import android.content.Intent;
import android.content.SharedPreferences;
import android.util.Log;

/**
 * Starts the autorun worker after a reboot, if the user turned autorun on.
 *
 * <p>This receiver deliberately does no work of its own. It used to call the
 * exploit directly on a background thread with {@code goAsync()}, which gives
 * roughly ten seconds of process lifetime — not enough for an su probe plus a
 * full run, so the thread was killed mid-flight and nothing was recorded. The
 * work now lives in {@link AutorunService}, which has no such budget.
 *
 * <p>Gating is by preference only, never by component-enabled state: a receiver
 * declared {@code enabled="false"} in the manifest is not delivered broadcasts
 * on some ROMs even after {@code setComponentEnabledSetting()} turns it back
 * on, so the component stays enabled and returns early instead.
 */
public class BootReceiver extends BroadcastReceiver {

    private static final String TAG = "DFRoot/Boot";
    static final String PREFS = "dfroot";
    static final String KEY_AUTORUN = "autorun";

    /** Outcome of the last autorun, so the UI can explain itself. */
    static final String KEY_LAST_RESULT = "last_boot_result";

    /**
     * Whether this boot may still retry a failed run.
     *
     * <p>Defaults to true so the very first boot gets its retry without any
     * setup. Consumed by the service before retrying and set back to true after
     * a second failure, which gives every boot one retry rather than one retry
     * per install.
     */
    static final String KEY_RETRY_LEFT = "retry_once_left";

    /**
     * The kernel boot id this install has already run in.
     *
     * <p>The hard one-run-per-boot rule. Three separate things can start a run
     * — {@code LOCKED_BOOT_COMPLETED}, {@code BOOT_COMPLETED}, and a user tap —
     * and on some ROMs a fourth (an incidental broadcast) is delivered after an
     * unlock. Gating each entry point individually still leaves the ordering
     * between them undefined; this key makes the outcome independent of which
     * one arrives first, because they all compare against the same value.
     *
     * <p>{@code /proc/sys/kernel/random/boot_id} is regenerated by the kernel on
     * every boot and is stable within one, which is exactly the granularity
     * needed. It is read rather than {@code SystemClock.elapsedRealtime()}
     * because a stored uptime is only a guess at whether a reboot happened.
     */
    static final String KEY_LAST_BOOT_ID = "last_boot_id";

    /**
     * How long after the kernel starts a boot broadcast is still believed.
     *
     * <p>Five minutes. A real boot broadcast lands within seconds, so this only
     * has to absorb a slow cold boot with dexopt and a receiver queued behind
     * other boot work. Every re-delivery seen on the reference device arrived at
     * an uptime measured in hours, so the window has three orders of magnitude
     * of headroom.
     *
     * <p>Wrong in the strict direction only: a boot that somehow takes longer
     * than this does not autorun, which is recoverable (open the app and tap the
     * button). Wrong in the loose direction would mean running when the user did
     * not ask, which is the bug being fixed.
     */
    static final long BOOT_WINDOW_MS = 5 * 60 * 1000L;

    @Override
    public void onReceive(Context context, Intent intent) {
        String action = intent == null ? null : intent.getAction();

        // Log before any decision, and log the ignored cases too. "The receiver
        // was never called" and "it was called and bailed out" look identical
        // from the outside, and telling them apart is the whole point.
        //
        // argv/flags and the sender matter as much as the action: a broadcast
        // delivered with FLAG_RECEIVER_REGISTERED_ONLY_BEFORE_BOOT, or one that
        // carries extras only the system would add, distinguishes a real system
        // delivery from something calling sendBroadcast by hand.
        StringBuilder meta = new StringBuilder("receiver: action=" + action);
        if (intent != null) {
            meta.append(" flags=0x").append(Integer.toHexString(intent.getFlags()));
            meta.append(" from=").append(intent.getPackage());
            java.util.Set<String> keys = intent.getExtras() == null
                    ? null : intent.getExtras().keySet();
            if (keys != null && !keys.isEmpty()) {
                meta.append(" extras=").append(keys);
            }
        } else {
            meta.append(" (intent==null)");
        }
        meta.append(" uptime=").append(android.os.SystemClock.elapsedRealtime() / 1000).append('s');
        meta.append(" autorun=").append(autorunOn(context));
        meta.append(" ver=").append(versionOf(context));
        BootLog.i(context, meta.toString());

        if (Intent.ACTION_MY_PACKAGE_REPLACED.equals(action)) {
            // Not listened for any more (see the manifest), but ROMs that
            // deliver it anyway must not fall through to the boot path.
            BootLog.i(context, "ignored: package replaced");
            return;
        }
        boolean isBoot = Intent.ACTION_BOOT_COMPLETED.equals(action)
                || Intent.ACTION_LOCKED_BOOT_COMPLETED.equals(action);
        if (!isBoot) {
            BootLog.i(context, "ignored: not a boot broadcast");
            return;
        }
        // Is this broadcast actually about the boot we are in?
        //
        // Some ROMs re-deliver BOOT_COMPLETED long after the device finished
        // booting — on unlock, on user switch, or on their own schedule. On the
        // reference device both actions arrived seven times in seven minutes
        // across a two-day uptime, and the first of those runs is not
        // distinguishable from a real boot by action name or by extra.
        //
        // Uptime is the signal that separates them: a genuine boot broadcast is
        // delivered within seconds of the kernel starting, so elapsedRealtime()
        // is tiny. A re-delivery happens at whatever uptime the device has
        // reached — minutes or days. A boot broadcast arriving when the device
        // has been up for longer than the window is therefore not about the
        // boot, and running on it is exactly the "it executed on its own"
        // behaviour this guard exists to stop.
        //
        // The window is generous on purpose: a slow cold boot plus dexopt plus
        // the receiver being queued behind other boot work can take a couple of
        // minutes, and a false negative here means autorun silently never runs.
        long up = android.os.SystemClock.elapsedRealtime();
        if (up > BOOT_WINDOW_MS) {
            BootLog.i(context, "boot: ignoring stale " + action
                    + " (uptime " + (up / 1000) + "s > " + (BOOT_WINDOW_MS / 1000)
                    + "s, device did not just boot)");
            return;
        }
        if (!autorunOn(context)) {
            BootLog.i(context, "boot: autorun disabled, nothing to do");
            return;
        }
        // The hard stop: one run per boot, whichever broadcast gets here first.
        // LOCKED_BOOT_COMPLETED and BOOT_COMPLETED both arrive on a normal
        // unlock, and the second one would otherwise start a second run once
        // the first had finished (the service's own `running` flag only covers
        // overlapping starts, not sequential ones).
        if (alreadyRanThisBoot(context)) {
            BootLog.i(context, "boot: already ran this boot, ignoring " + action);
            return;
        }
        claimThisBoot(context);

        BootLog.sessionStart(context, "boot broadcast " + action);
        BootLog.i(context, "boot: handing off to service");
        try {
            AutorunService.start(context);
            BootLog.i(context, "boot: service start returned normally");
        } catch (Exception e) {
            // A foreground service start can be refused (background start
            // restrictions, missing notification permission on some builds).
            // Record it instead of letting it escape a receiver.
            BootLog.e(context, "boot: could not start autorun service", e);
            setLastResult(context, "failed: service start");
            setAutorun(context, false);
        }
    }

    /**
     * Is autorun on?
     *
     * <p>Read from device-encrypted storage, with a one-time migration from the
     * credential-encrypted location used by earlier builds. Without the
     * migration every existing install would read {@code false} here and stop
     * autorunning after an update — the setting would look like it had been
     * silently turned off.
     *
     * <p>The migration only runs when the device-protected file has no value
     * yet, and the old value is left in place rather than deleted: deleting
     * would need another credential-encrypted write at a point where storage
     * may still be locked, and a stale duplicate is harmless.
     */
    static boolean autorunOn(Context context) {
        SharedPreferences de = prefs(context);
        if (de.contains(KEY_AUTORUN)) {
            return de.getBoolean(KEY_AUTORUN, false);
        }
        // Not migrated yet — or genuinely never set. Try the old location, but
        // only if storage is readable; at locked boot it is not, and in that
        // case the honest answer is "no" until the user unlocks.
        try {
            SharedPreferences old = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
            if (old.contains(KEY_AUTORUN)) {
                boolean v = old.getBoolean(KEY_AUTORUN, false);
                de.edit().putBoolean(KEY_AUTORUN, v).commit();
                android.util.Log.i("DFRoot/Boot", "migrated autorun=" + v + " to device-protected storage");
                return v;
            }
        } catch (IllegalStateException locked) {
            // Credential-encrypted storage is not available yet. This is the
            // exact case the old code crashed on; it is not an error.
            android.util.Log.i("DFRoot/Boot", "autorun: storage locked, treating as off for now");
        }
        return false;
    }

    /**
     * Version string for the log header.
     *
     * <p>Read from PackageManager rather than BuildConfig: this project is built
     * with a hand-rolled aapt2 + javac + d8 pipeline and has no generated
     * BuildConfig class.
     */
    private static String versionOf(Context context) {
        try {
            android.content.pm.PackageInfo pi = context.getPackageManager()
                    .getPackageInfo(context.getPackageName(), 0);
            return pi.versionName + "(" + pi.getLongVersionCode() + ")";
        } catch (Exception e) {
            return "?";
        }
    }

    static void setAutorun(Context context, boolean on) {
        prefs(context).edit().putBoolean(KEY_AUTORUN, on).commit();
    }

    /**
     * Wait for su to become usable, polling until the deadline.
     *
     * <p>Needed because the exploit finishing does not mean the su daemon is
     * serving yet: the module is loaded and SELinux is dropped inside the same
     * run, and the daemon that answers {@code su} comes up asynchronously
     * afterwards. A single immediate check races against that and reports "no
     * root" on a run that actually succeeded.
     *
     * <p>Each attempt is cheap, but the first one may have to wait out a su
     * prompt that cannot be shown at boot, so the per-attempt timeout is kept
     * short and the loop bounded by {@code deadlineMs} rather than by a count.
     */
    static boolean waitForSu(Context context, long deadlineMs, Log sink) {
        long start = System.currentTimeMillis();
        int attempt = 0;
        while (System.currentTimeMillis() - start < deadlineMs) {
            attempt++;
            ExploitRunner.ShellResult r = ExploitRunner.suId(4);
            if (r != null && r.rc == 0 && r.output.contains("uid=0")) {
                sink.i("worker: su available after "
                        + (System.currentTimeMillis() - start) + "ms (" + attempt + " attempts)");
                return true;
            }
            try {
                // 1s between attempts: enough for the daemon to finish binding,
                // short enough that a successful boot still sweeps promptly.
                Thread.sleep(1000);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                return false;
            }
        }
        sink.i("worker: su unavailable after " + deadlineMs + "ms (" + attempt + " attempts)");
        return false;
    }

    /**
     * Minimal logging surface, so this helper does not depend on BootLog's
     * concrete type and stays usable from a service without a Context dance.
     */
    interface Log {
        void i(String message);
    }

    static boolean retryOnceLeft(Context context) {
        return prefs(context).getBoolean(KEY_RETRY_LEFT, true);
    }

    // ------------------------------------------------------------------
    // One run per boot
    // ------------------------------------------------------------------

    /** The current kernel boot id, or {@code null} if it cannot be read. */
    private static String bootId() {
        java.io.BufferedReader r = null;
        try {
            r = new java.io.BufferedReader(new java.io.FileReader(
                    "/proc/sys/kernel/random/boot_id"));
            String id = r.readLine();
            return id == null || id.trim().isEmpty() ? null : id.trim();
        } catch (Exception e) {
            android.util.Log.w("DFRoot/Boot", "cannot read boot_id", e);
            return null;
        } finally {
            if (r != null) {
                try {
                    r.close();
                } catch (Exception ignored) {
                }
            }
        }
    }

    /**
     * Has a run already started during the current boot?
     *
     * <p>Returns false when the boot id cannot be read: the marker is a
     * convenience, not a security boundary, and refusing to run because /proc
     * is unreadable would be worse than running twice.
     */
    static boolean alreadyRanThisBoot(Context context) {
        String now = bootId();
        if (now == null) {
            return false;
        }
        return now.equals(prefs(context).getString(KEY_LAST_BOOT_ID, null));
    }

    /**
     * Claim the current boot for a run.
     *
     * <p>Written <em>before</em> the run starts, not after: two broadcasts can
     * arrive close together, and recording only on completion would let both
     * pass the check. Claiming first means the second one sees the claim and
     * stops.
     */
    static void claimThisBoot(Context context) {
        String now = bootId();
        if (now != null) {
            prefs(context).edit().putString(KEY_LAST_BOOT_ID, now).commit();
        }
    }

    /** Forget the claim, so the next boot's guard starts clean. */
    static void clearBootClaim(Context context) {
        prefs(context).edit().remove(KEY_LAST_BOOT_ID).commit();
    }

    static void setRetryOnceLeft(Context context, boolean left) {
        prefs(context).edit().putBoolean(KEY_RETRY_LEFT, left).commit();
    }

    static void setLastResult(Context context, String result) {
        prefs(context).edit().putString(KEY_LAST_RESULT, result).commit();
    }

    static String lastResult(Context context) {
        return prefs(context).getString(KEY_LAST_RESULT, null);
    }

    static void clearLastResult(Context context) {
        prefs(context).edit().remove(KEY_LAST_RESULT).commit();
    }

    /**
     * Preferences on device-encrypted storage, not credential-encrypted.
     *
     * <p>This is not a style choice — it is required for the receiver to work
     * at all. {@code BootReceiver} is {@code directBootAware}, so it is invoked
     * for {@code LOCKED_BOOT_COMPLETED}, which is delivered <em>before</em> the
     * user unlocks the device. Credential-encrypted storage does not exist yet
     * at that point, and any access throws:
     *
     * <pre>
     *   IllegalStateException: SharedPreferences in credential encrypted
     *   storage are not available until after user (id 0) is unlocked
     * </pre>
     *
     * <p>That exception used to escape {@code onReceive}, so the locked-boot
     * broadcast crashed the receiver and every setting read below was lost.
     * Device-encrypted storage is available from the first moment of boot, so
     * every key in this file lives there.
     */
    private static SharedPreferences prefs(Context context) {
        Context de = context.createDeviceProtectedStorageContext();
        if (de == null) {
            // No device-protected storage means the platform is old enough that
            // this distinction does not exist; the normal context is correct.
            de = context;
        }
        return de.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
    }
}