#!/usr/bin/env python3
"""
gen_kmi_inc.py - generate kmi_table.inc from the .ko files in jni/ko/.

Why generate instead of hand-writing the table: the list of supported KMIs
must match the modules actually bundled in the APK, and a hand-maintained
table silently drifts (add a .ko, forget the entry, and the module is dead
weight; or add an entry, forget the .ko, and the link fails). Generating it
keeps the two in sync by construction.

Module file naming contract:  dfroot-<android>-<major>.<minor>.ko
examples:                     dfroot-android13-5.15.ko
                              dfroot-android14-6.1.ko

Output (kmi_table.inc) declares:
  extern char <sym>_start[], <sym>_end[];   for every module
  KMI_NAMES   - string literal initialiser for the name array
  KMI_IMAGES  - struct initialiser for the image table

The corresponding .incbin directives live in exp.c, which is generated by
the same script alongside this table so the two cannot disagree.
"""
import os
import re
import sys

PAT = re.compile(r"^dfroot-android(\d+)-(\d+)\.(\d+)\.ko$")


def symbol_for(android, major, minor):
    return "dfroot_ko_%d_%d_%d" % (android, major, minor)


def collect(ko_dir):
    mods = []
    for name in sorted(os.listdir(ko_dir)):
        m = PAT.match(name)
        if not m:
            continue
        android, major, minor = (int(g) for g in m.groups())
        mods.append((android, major, minor, name))
    # Stable, human-sensible order: android release, then kernel version.
    mods.sort(key=lambda t: (t[0], t[1], t[2]))
    return mods


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: gen_kmi_inc.py <jni_dir>\n")
        return 2
    jni = sys.argv[1]
    ko_dir = os.path.join(jni, "ko")
    if not os.path.isdir(ko_dir):
        sys.stderr.write("gen_kmi_inc: no %s\n" % ko_dir)
        return 1

    mods = collect(ko_dir)
    if not mods:
        sys.stderr.write("gen_kmi_inc: no dfroot-*.ko in %s\n" % ko_dir)
        return 1

    out = []
    hdr = "/* GENERATED by gen_kmi_inc.py - do not edit. */\n"
    out.append(hdr)

    for android, major, minor, _ in mods:
        sym = symbol_for(android, major, minor)
        out.append("extern char %s_start[], %s_end[];\n" % (sym, sym))

    out.append("\n#define KMI_NAMES { \\\n")
    for android, major, minor, name in mods:
        out.append('    "%s", \\\n' % name)
    out.append("}\n")

    out.append("\n#define KMI_IMAGES { \\\n")
    for android, major, minor, _ in mods:
        sym = symbol_for(android, major, minor)
        out.append("    { %d, %d, %d, %s_start, %s_end }, \\\n"
                   % (android, major, minor, sym, sym))
    out.append("}\n")

    with open(os.path.join(jni, "kmi_table.inc"), "w") as f:
        f.write("".join(out))

    # The .incbin block. Each module gets labelled start/end symbols so the
    # selection table can refer to its byte range. Written to its own .inc
    # so exp.c carries one stable .include instead of eight hand-edited
    # lines that drift whenever a module is added or renamed.
    blobs = [hdr]
    for android, major, minor, name in mods:
        sym = symbol_for(android, major, minor)
        blobs.append(
            ".global %s_start\n.global %s_end\n"
            "%s_start:\n"
            ".incbin \"ko/%s\"\n"
            "%s_end:\n" % (sym, sym, sym, name, sym))
    with open(os.path.join(jni, "kmi_blobs.inc"), "w") as f:
        f.write("".join(blobs))
    # The Java side needs the same list to show which modules shipped in this
    # APK. It used to be a hand-maintained array in KernelInfo.java, which the
    # README claimed was automatic and was not: adding a module and rerunning
    # the build left the settings screen showing the previous set. Emitting a
    # tiny Java source file here means both sides come from this one scan.
    java_out = ["// Generated by jni/gen_kmi_inc.py - do not edit.",
                "package df.root;",
                "",
                "/** Module names bundled in this build; see gen_kmi_inc.py. */",
                "final class KmiModules {",
                "",
                "    private KmiModules() {",
                "    }",
                "",
                "    static final String[] MODULES = {"]
    for android, major, minor, name in mods:
        java_out.append('        "dfroot-android%d-%d.%d.ko",' % (android, major, minor))
    java_out.append("    };")
    java_out.append("}")
    java_out.append("")
    java_path = os.path.join(jni, "..", "java", "df", "root", "KmiModules.java")
    java_path = os.path.normpath(java_path)
    os.makedirs(os.path.dirname(java_path), exist_ok=True)
    with open(java_path, "w") as f:
        f.write("\n".join(java_out))
    sys.stderr.write("gen_kmi_inc: %d module(s): %s\n"
                     % (len(mods), ", ".join(n for *_, n in mods)))
    return 0


if __name__ == "__main__":
    sys.exit(main())